"""Generate the README's test-count SVG from explicit CHANGELOG.md records.

Run with ``python docs/make_charts.py`` from any directory. Releases without
a recorded test count are skipped; the current test suite is not a data source.
"""

import re
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def test_history(changelog: str) -> list[tuple[str, int]]:
    """Read release headings and explicit 'N tests passed/passing' records."""
    records: dict[str, int] = {}
    for section in re.split(r"(?m)^## ", changelog)[1:]:
        heading, _, body = section.partition("\n")
        version = re.match(r"(\d+\.\d+\.\d+)\b", heading)
        if version is None:
            continue
        for match in re.finditer(r"\b(\d[\d,]*)\s+tests\s+(?:passed|passing)\b", body):
            release = version.group(1)
            count = int(match.group(1).replace(",", ""))
            if release in records and records[release] != count:
                raise ValueError(f"Conflicting test counts for {release}")
            records[release] = count
    return sorted(records.items(), key=lambda record: tuple(map(int, record[0].split("."))))


def render_chart(records: list[tuple[str, int]]) -> str:
    """Draw bars from zero, with exact count labels and accessible source data."""
    if not records:
        raise ValueError("CHANGELOG.md has no explicit release test counts")
    width, height = 960, 400
    left, right, top, bottom = 96, 912, 112, 300
    maximum = max(count for _, count in records)
    step = max(1, 10 ** (len(str(maximum)) - 1) // 2)
    ceiling = max(step, ((maximum + step - 1) // step) * step)
    slot = (right - left) / len(records)
    bar_width = min(160, slot * 0.65)
    data = "; ".join(f"v{version}: {count} tests passed" for version, count in records)
    svg = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by docs/make_charts.py; source: CHANGELOG.md. -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title description">',
        '  <title id="title">Test counts recorded in CHANGELOG.md</title>',
        f'  <desc id="description">{escape(data)}. '
        "Releases without a recorded count are omitted; no growth is inferred.</desc>",
        '  <rect width="960" height="400" rx="18" fill="#0f172a"/>',
        '  <g font-family="system-ui, sans-serif" fill="#e2e8f0">',
        '    <text x="36" y="44" font-size="24" font-weight="700">Recorded test counts</text>',
        '    <text x="36" y="72" font-size="15" fill="#cbd5e1">'
        "Only explicit changelog records · unreported releases skipped</text>",
    ]
    for tick in range(0, ceiling + 1, step):
        y = bottom - tick / ceiling * (bottom - top)
        svg.extend(
            [
                f'    <path d="M {left} {y:.2f} H {right}" stroke="#334155"/>',
                f'    <text x="82" y="{y + 5:.2f}" text-anchor="end" font-size="14">{tick}</text>',
            ]
        )
    svg.extend(
        [
            f'    <path d="M {left} {top} V {bottom} H {right}" fill="none" stroke="#94a3b8"/>',
            '    <text transform="translate(34 206) rotate(-90)" '
            'text-anchor="middle" font-size="14">Passing tests</text>',
        ]
    )
    for index, (version, count) in enumerate(records):
        x = left + slot * (index + 0.5)
        bar_height = count / ceiling * (bottom - top)
        y = bottom - bar_height
        svg.extend(
            [
                f'    <rect x="{x - bar_width / 2:.2f}" y="{y:.2f}" '
                f'width="{bar_width:.2f}" height="{bar_height:.2f}" fill="#5eead4">'
                f"<title>v{escape(version)}: {count} tests passed</title></rect>",
                f'    <text x="{x:.2f}" y="{y - 12:.2f}" text-anchor="middle" '
                f'font-size="22" font-weight="700" fill="#5eead4">{count}</text>',
                f'    <text x="{x:.2f}" y="324" text-anchor="middle" '
                f'font-size="15">v{escape(version)}</text>',
            ]
        )
    svg.extend(
        [
            '    <text x="504" y="352" text-anchor="middle" font-size="14">Release version</text>',
            '    <text x="36" y="382" font-size="13" fill="#cbd5e1">'
            "Source: CHANGELOG.md · missing counts are never estimated</text>",
            "  </g>",
            "</svg>",
        ]
    )
    return "\n".join(svg) + "\n"


def main() -> None:
    records = test_history((ROOT / "CHANGELOG.md").read_text(encoding="utf-8"))
    target = ROOT / "docs" / "assets" / "tests-growth.svg"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_chart(records), encoding="utf-8")
    print(f"Wrote {target.relative_to(ROOT)} from {len(records)} recorded release(s)")


if __name__ == "__main__":
    main()
